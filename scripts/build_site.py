#!/usr/bin/env python3
"""Build the public GitHub Pages site into a git-ignored output directory.

Usage: python scripts/build_site.py OUTPUT_DIR

The public Game Facts are the only source of facts. Datasets and data pages are
generated from their tables; curated prose lives in site/content/. The generator
reads no original game data and writes no original text, maps, art, music or code.
See docs/SITE.md for the structure and how to add a page or dataset.
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

import gamefacts_public
import site_data
import site_pages_content
import site_pages_data
import site_pages_home
import site_pages_hood
import site_pages_play
import site_data_play
from site_context import Context

ROOT = Path(__file__).resolve().parents[1]
MARKER = ".site-build"
NOT_FOUND = (
    "<!doctype html>\n"
    '<html lang="en"><head><meta charset="utf-8">'
    '<meta name="viewport" content="width=device-width, initial-scale=1">'
    "<title>Page not found | Ultima V Redux</title>"
    "<style>body{background:#000;color:#fff;font:16px/1.5 system-ui,sans-serif;"
    "max-width:60ch;margin:10vh auto;padding:0 16px}h1{color:#ff5;"
    "font-family:ui-monospace,monospace}a{color:#8c8cff}</style></head><body>"
    "<h1>Page not found</h1><p>That page is not part of the Ultima V Redux site. "
    "Return to the home page from the address bar, or visit the "
    '<a href="https://github.com/bradhannah/UltimaVRedux">project on GitHub</a>.'
    "</p></body></html>\n"
)


def prepare_output(out: Path) -> None:
    """Create an empty output directory, wiping only a previous site build."""
    out = out.resolve()
    if out.exists():
        gamefacts_public.require(
            not any(out.iterdir()) or (out / MARKER).exists(),
            f"{out} is not empty and is not a previous site build",
        )
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("Generated by scripts/build_site.py\n", encoding="utf-8")
    (out / ".nojekyll").write_text("", encoding="utf-8")


def write_json(path: Path, data: object) -> None:
    """Write stable, human-readable JSON."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def write_datasets(ctx: Context, out: Path) -> None:
    """Publish each dataset and an index listing them."""
    listing = []
    for name, dataset in ctx.datasets.items():
        write_json(out / "data" / f"{name}.json", dataset)
        records = site_data.objects(dataset["records"])
        listing.append(
            {
                "dataset": name,
                "title": dataset["title"],
                "path": f"{name}.json",
                "records": len(records),
                "source": dataset["source"],
            }
        )
    write_json(
        out / "data" / "index.json",
        {
            "schema_version": 1,
            "generator": "scripts/build_site.py",
            "datasets": listing,
        },
    )


def build(root: Path, out: Path) -> Context:
    """Generate the whole site under `out` and return the build context."""
    documents, rules = gamefacts_public.load_catalog(
        root, "docs/gamefacts/catalog.json"
    )
    content = root / "site" / "content"
    ctx = Context(
        root=root,
        rules=rules,
        documents=documents,
        datasets=site_data.build_all(rules),
        content=content,
    )
    ctx.notice = str(ctx.load("redux.json")["fan_notice"])
    ctx.datasets.update(site_data_play.build_all(rules, ctx.datasets["equipment"]))
    for build_page in site_pages_data.PAGE_BUILDERS + site_pages_play.PAGE_BUILDERS:
        build_page(ctx)
    site_pages_content.build_all(ctx)
    site_pages_hood.build_all(ctx)
    site_pages_home.build_all(ctx)
    prepare_output(out)
    for path, document in ctx.pages.items():
        target = out / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(document, encoding="utf-8")
    shutil.copytree(root / "site" / "static", out / "assets")
    (out / "404.html").write_text(NOT_FOUND, encoding="utf-8")
    write_datasets(ctx, out)
    return ctx


def main(argv: list[str]) -> int:
    """Parse arguments and build the site."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("output", type=Path, help="git-ignored output directory")
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root")
    args = parser.parse_args(argv)
    ctx = build(args.root.resolve(), args.output)
    pages, datasets = len(ctx.pages), len(ctx.datasets)
    print(f"built {pages} pages and {datasets} datasets into {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
