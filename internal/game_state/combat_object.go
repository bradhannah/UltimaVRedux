package game_state

import (
	"github.com/bradhannah/UltimaVRedux/internal/references"
	"github.com/bradhannah/UltimaVRedux/internal/sprites/indexes"
)

const combatChestLockTrapBit = 0x80

// CombatObjectID identifies one object lifetime within an encounter. Zero is unassigned.
// Slots, positions and object contents may repeat; an admitted lifetime never does.
type CombatObjectID uint64

// CombatChestIdentity is a detached reference to the exact chest selected by an action.
// Its identity is meaningful only in the CombatState that admitted the chest.
type CombatChestIdentity struct {
	Position references.Position
	ObjectID CombatObjectID
}

// CombatObject is an encounter-local object rendered above combat terrain.
// Number preserves the original object-number encoding used by chest mechanics.
type CombatObject struct {
	lifetimeID     CombatObjectID
	position       references.Position
	sprite         indexes.SpriteIndex
	number         int
	blocksMovement bool
	item           references.Item
	quantity       uint16
	searchable     bool
	// originalObjectSlot is one-based; zero means the object has not been admitted.
	originalObjectSlot uint8
	chestAssessment    references.ChestAssessment
}

// LifetimeID survives value copies and slice movement, but not removal and readmission.
func (object CombatObject) LifetimeID() CombatObjectID { return object.lifetimeID }

// HasChestIdentity checks a live chest without substituting another object in its slot.
func (combatState *CombatState) HasChestIdentity(identity CombatChestIdentity) bool {
	if identity.ObjectID == 0 {
		return false
	}
	for _, object := range combatState.objects {
		if object.lifetimeID == identity.ObjectID && object.Position() == identity.Position && object.IsChest() {
			return true
		}
	}

	return false
}

// NewCombatChest creates a chest using the original value and shared lock/trap bit.
func NewCombatChest(position references.Position, treasureValue int, lockedAndTrapped bool) CombatObject {
	if treasureValue < 1 || treasureValue >= combatChestLockTrapBit {
		panic("combat chest treasure value must be between 1 and 127")
	}

	number := treasureValue
	if lockedAndTrapped {
		number |= combatChestLockTrapBit
	}

	return CombatObject{
		position:           position,
		sprite:             indexes.Chest,
		number:             number,
		blocksMovement:     true,
		item:               nil,
		quantity:           0,
		searchable:         false,
		originalObjectSlot: 0,
	}
}

// NewCombatCorpse creates a walkable monster corpse that can be searched.
func NewCombatCorpse(position references.Position) CombatObject {
	return CombatObject{
		position:           position,
		sprite:             indexes.Splat,
		number:             0,
		blocksMovement:     false,
		item:               nil,
		quantity:           0,
		searchable:         true,
		originalObjectSlot: 0,
	}
}

// NewCombatDeadPC creates the original walkable DEAD_PC battlefield marker.
func NewCombatDeadPC(position references.Position) CombatObject {
	return CombatObject{
		position:           position,
		sprite:             indexes.DeadBody,
		number:             0,
		blocksMovement:     false,
		item:               nil,
		quantity:           0,
		searchable:         false,
		originalObjectSlot: 0,
	}
}

// NewCombatLooseItem creates a walkable item generated by opening or searching.
func NewCombatLooseItem(
	position references.Position,
	item references.Item,
	quantity uint16,
	sprite indexes.SpriteIndex,
) CombatObject {
	if item == nil || quantity == 0 {
		panic("combat loose item requires an item and positive quantity")
	}

	return CombatObject{
		position:           position,
		sprite:             sprite,
		number:             0,
		blocksMovement:     false,
		item:               item,
		quantity:           quantity,
		searchable:         false,
		originalObjectSlot: 0,
	}
}

// NewCombatDungeonObject preserves a non-collectible fixed-room object descriptor.
// Authored corpses stay walkable like battle corpses. ref:COMBAT-0003
func NewCombatDungeonObject(
	position references.Position,
	sprite indexes.SpriteIndex,
	number int,
) CombatObject {
	return CombatObject{
		position:           position,
		sprite:             sprite,
		number:             number,
		blocksMovement:     !isCombatCorpseMarker(sprite),
		item:               nil,
		quantity:           0,
		searchable:         false,
		originalObjectSlot: 0,
	}
}

// Position returns the object's combat-grid position.
func (object CombatObject) Position() references.Position {
	return object.position
}

// Sprite returns the object's displayed sprite.
func (object CombatObject) Sprite() indexes.SpriteIndex {
	return object.sprite
}

// IsChest reports whether the object is a chest.
func (object CombatObject) IsChest() bool {
	return object.sprite == indexes.Chest
}

// isCombatCorpseMarker reports the original DEAD_PC and DEAD_MONST shapes, which
// never block movement. ref:COMBAT-0003
func isCombatCorpseMarker(sprite indexes.SpriteIndex) bool {
	return sprite == indexes.DeadBody || sprite == indexes.Splat
}

// IsCorpse reports whether the object is a searchable monster corpse.
func (object CombatObject) IsCorpse() bool {
	return object.sprite == indexes.Splat && object.searchable
}

// LooseItem returns the carried item and quantity for collectible objects.
func (object CombatObject) LooseItem() (references.ItemAndQuantity, bool) {
	if object.item == nil || object.quantity == 0 {
		var noItem references.ItemAndQuantity

		return noItem, false
	}

	return references.ItemAndQuantity{Item: object.item, Quantity: object.quantity}, true
}

// TreasureValue returns the chest's value without its lock/trap bit.
func (object CombatObject) TreasureValue() int {
	return object.number &^ combatChestLockTrapBit
}

// IsLockedAndTrapped reports whether the shared chest state bit is set.
func (object CombatObject) IsLockedAndTrapped() bool {
	return object.number&combatChestLockTrapBit != 0
}

// UnlockChest clears the shared trap bit and records safety after Jimmy or magic.
func (object *CombatObject) UnlockChest() {
	if !object.IsChest() {
		panic("UnlockChest called on non-chest combat object")
	}
	object.number &^= combatChestLockTrapBit
	object.chestAssessment = references.ChestSafe
}

// ChestAssessment returns this encounter-local object's inspection knowledge.
func (object CombatObject) ChestAssessment() references.ChestAssessment {
	return object.chestAssessment
}

// liveChest resolves the exact selected lifetime, never a replacement in its slot.
func (combatState *CombatState) liveChest(selected CombatObject) *CombatObject {
	for index := range combatState.objects {
		object := &combatState.objects[index]
		if selected.lifetimeID != 0 && object.lifetimeID == selected.lifetimeID && object.IsChest() &&
			object.Position() == selected.Position() {
			return object
		}
	}
	panic("selected combat chest disappeared during resolution")
}

// BlocksMovement reports whether combatants can enter the object's position.
func (object CombatObject) BlocksMovement() bool {
	return object.blocksMovement
}

// AddObject admits an encounter-local object into the lowest free original slot.
func (combatState *CombatState) AddObject(object CombatObject) bool {
	slot, found := combatState.firstFreeOriginalObjectSlot(0, 1)
	if !found {
		return false
	}
	object.originalObjectSlot = encodeOriginalObjectSlot(slot)
	combatState.insertObjectByOriginalSlot(object)

	return true
}

// addLootObject reproduces additem/findempt's descending scan. Slot zero is the
// original failure sentinel and therefore cannot admit generated chest loot.
func (combatState *CombatState) addLootObject(object CombatObject) bool {
	slot, found := combatState.firstFreeOriginalObjectSlot(sourceCombatQueueSlots-1, -1)
	if !found || slot == 0 {
		return false
	}
	object.originalObjectSlot = encodeOriginalObjectSlot(slot)
	combatState.insertObjectByOriginalSlot(object)

	return true
}

func (combatState *CombatState) insertObjectByOriginalSlot(object CombatObject) {
	// Every admission path (authored objects, loot, corpses and replacements)
	// passes here. Even readmitting a removed value creates a new lifetime.
	if combatState.lastObjectID == ^CombatObjectID(0) {
		panic("combat object lifetime IDs exhausted")
	}
	combatState.lastObjectID++
	object.lifetimeID = combatState.lastObjectID
	insertAt := len(combatState.objects)
	for index, existing := range combatState.objects {
		if existing.originalObjectSlot > object.originalObjectSlot {
			insertAt = index

			break
		}
	}
	combatState.objects = append(combatState.objects, CombatObject{})
	copy(combatState.objects[insertAt+1:], combatState.objects[insertAt:])
	combatState.objects[insertAt] = object
}

func (combatState *CombatState) transferCombatantObjectTo(
	identity CombatTurnIdentity,
	object CombatObject,
) bool {
	entry := combatState.TurnQueue.GetEntryByIdentity(identity)
	if entry == nil || entry.originalObjectSlot == 0 {
		return false
	}
	object.originalObjectSlot = entry.originalObjectSlot
	entry.originalObjectSlot = 0
	combatState.insertObjectByOriginalSlot(object)

	return true
}

func (combatState *CombatState) replaceObjectInOriginalSlot(previous, replacement CombatObject) {
	if previous.originalObjectSlot == 0 {
		panic("replacement object has no original slot")
	}
	replacement.originalObjectSlot = previous.originalObjectSlot
	if combatState.originalObjectSlotInUse(decodeOriginalObjectSlot(replacement.originalObjectSlot)) {
		panic("replacement original object slot is still occupied")
	}
	combatState.insertObjectByOriginalSlot(replacement)
}

// ObjectAt returns the topmost encounter-local object at a position.
func (combatState *CombatState) ObjectAt(position references.Position) (CombatObject, bool) {
	return combatState.objectAtMatching(position, func(CombatObject) bool { return true })
}

func (combatState *CombatState) firstGettableObjectAt(position references.Position) (CombatObject, bool) {
	for _, object := range combatState.objects {
		_, collectible := object.LooseItem()
		if object.Position() == position && (object.IsChest() || collectible) {
			return object, true
		}
	}

	var noObject CombatObject

	return noObject, false
}

func (combatState *CombatState) objectAtMatching(
	position references.Position,
	matches func(CombatObject) bool,
) (CombatObject, bool) {
	for index := len(combatState.objects) - 1; index >= 0; index-- {
		object := combatState.objects[index]
		if object.Position() == position && matches(object) {
			return object, true
		}
	}

	var noObject CombatObject

	return noObject, false
}

func (combatState *CombatState) takeObjectAt(
	position references.Position,
	matches func(CombatObject) bool,
) (CombatObject, bool) {
	for index := len(combatState.objects) - 1; index >= 0; index-- {
		object := combatState.objects[index]
		if object.Position() != position || !matches(object) {
			continue
		}

		combatState.objects = append(combatState.objects[:index], combatState.objects[index+1:]...)

		return object, true
	}

	var noObject CombatObject

	return noObject, false
}

func (combatState *CombatState) takeFirstObjectAt(
	position references.Position,
	matches func(CombatObject) bool,
) (CombatObject, bool) {
	for index, object := range combatState.objects {
		if object.Position() != position || !matches(object) {
			continue
		}

		combatState.objects = append(combatState.objects[:index], combatState.objects[index+1:]...)

		return object, true
	}

	var noObject CombatObject

	return noObject, false
}

func (combatState *CombatState) unlockChestAt(position references.Position) bool {
	chest, found := combatState.objectAtMatching(position, CombatObject.IsChest)
	if found {
		combatState.liveChest(chest).UnlockChest()
	}

	return found
}

// HasObjectAt reports whether an encounter-local object occupies a position.
func (combatState *CombatState) HasObjectAt(position references.Position) bool {
	_, found := combatState.ObjectAt(position)

	return found
}

// HasBlockingObjectAt reports whether an object prevents movement into a position.
func (combatState *CombatState) HasBlockingObjectAt(position references.Position) bool {
	for _, object := range combatState.objects {
		if object.Position() == position && object.BlocksMovement() {
			return true
		}
	}

	return false
}

func (combatState *CombatState) hasMonsterBlockingObjectAt(position references.Position) bool {
	for _, object := range combatState.objects {
		if object.Position() != position {
			continue
		}
		if !isCombatCorpseMarker(object.sprite) {
			return true
		}
	}

	return false
}

// ObjectCount returns the number of encounter-local objects.
func (combatState *CombatState) ObjectCount() int {
	return len(combatState.objects)
}

func (combatState *CombatState) hasFreeOriginalObjectSlot() bool {
	_, found := combatState.firstFreeOriginalObjectSlot(0, 1)

	return found
}

func (combatState *CombatState) originalObjectSlotCount() int {
	used := 0
	for slot := range sourceCombatQueueSlots {
		if combatState.originalObjectSlotInUse(slot) {
			used++
		}
	}

	return used
}

func (combatState *CombatState) registerCombatantObject(identity CombatTurnIdentity) bool {
	entry := combatState.TurnQueue.GetEntryByIdentity(identity)
	if entry == nil || entry.originalObjectSlot != 0 {
		return false
	}
	slot, found := combatState.firstFreeOriginalObjectSlot(0, 1)
	if !found {
		return false
	}
	entry.originalObjectSlot = encodeOriginalObjectSlot(slot)

	return true
}

func (combatState *CombatState) firstFreeOriginalObjectSlot(start, step int) (int, bool) {
	for slot := start; slot >= 0 && slot < sourceCombatQueueSlots; slot += step {
		if !combatState.originalObjectSlotInUse(slot) {
			return slot, true
		}
	}

	return 0, false
}

func (combatState *CombatState) originalObjectSlotInUse(slot int) bool {
	encoded := encodeOriginalObjectSlot(slot)
	if combatState.TurnQueue != nil {
		for _, entry := range combatState.TurnQueue.entries {
			if entry.originalObjectSlot == encoded {
				return true
			}
		}
	}
	for _, field := range combatState.fields {
		if field.originalObjectSlot == encoded {
			return true
		}
	}
	for _, object := range combatState.objects {
		if object.originalObjectSlot == encoded {
			return true
		}
	}

	return false
}

func encodeOriginalObjectSlot(slot int) uint8 {
	if slot < 0 || slot >= sourceCombatQueueSlots {
		panic("original object slot is out of range")
	}

	return uint8(slot + 1)
}

func decodeOriginalObjectSlot(slot uint8) int {
	if slot == 0 {
		panic("original object slot is unassigned")
	}

	return int(slot) - 1
}
